CREATE DATABASE IF NOT EXISTS eduadvisor CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE eduadvisor;

CREATE TABLE IF NOT EXISTS students (
  student_id VARCHAR(30) NOT NULL PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  class_code VARCHAR(30) NULL,
  email VARCHAR(150) NULL,
  phone VARCHAR(30) NULL,
  cpa DECIMAL(3,2) NOT NULL DEFAULT 0.00,
  gpa_hk DECIMAL(3,2) NOT NULL DEFAULT 0.00,
  prev_gpa DECIMAL(3,2) NOT NULL DEFAULT 0.00,
  accumulated_credits INT NOT NULL DEFAULT 0,
  debt_credits INT NOT NULL DEFAULT 0,
  failed_courses_count INT NOT NULL DEFAULT 0,
  last_advising VARCHAR(50) NULL,
  advising_note TEXT NULL,
  advising_history JSON NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS course_grades (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  student_id VARCHAR(30) NOT NULL,
  course_code VARCHAR(30) NOT NULL,
  course_name VARCHAR(150) NOT NULL,
  semester VARCHAR(30) NOT NULL,
  credits TINYINT UNSIGNED NOT NULL,
  attendance DECIMAL(4,2) NOT NULL,
  midterm DECIMAL(4,2) NOT NULL,
  final DECIMAL(4,2) NOT NULL,
  total_score DECIMAL(4,2) NOT NULL,
  grade_point DECIMAL(3,1) NOT NULL,
  letter_grade VARCHAR(4) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_grade_student FOREIGN KEY (student_id) REFERENCES students(student_id) ON DELETE CASCADE,
  UNIQUE KEY uq_student_course_semester (student_id, course_code, semester)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(120) NOT NULL,
  role ENUM('ADMIN','CVHT') NOT NULL DEFAULT 'CVHT',
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS advising_sessions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  student_id VARCHAR(30) NOT NULL,
  advisor_username VARCHAR(60) NOT NULL,
  advising_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  content TEXT NOT NULL,
  commitment TEXT NULL,
  channel VARCHAR(50) DEFAULT 'Trực tiếp',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_advising_student FOREIGN KEY (student_id) REFERENCES students(student_id) ON DELETE CASCADE,
  INDEX idx_advising_student_date(student_id, advising_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
